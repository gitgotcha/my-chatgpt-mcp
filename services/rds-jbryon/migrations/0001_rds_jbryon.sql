-- RDS-JBryon storage, migration 0001 (protocol "rds-jbryon", apiVersion 1).
--
-- Design basis: docs/superpowers/specs/2026-10-26-rds-jbryon-design.md §4–§12.
--
-- Single-user by construction: this schema has no user/account/credential
-- table, no registration table and no Drive/archive table. Every row belongs
-- to the one workspace identified by workspace_meta.id = 1; workspace_epoch
-- is a random workspace identity (not a user identity) rotated on a full reset.
--
-- Minimal-implementation deviations are recorded in src/store.js's header and
-- in the delivery report:
--   * accept commits D1 only; the Worker dispatches tasks to Queue after accept,
--     using task state and lease fields as the durable handoff/recovery record,
--   * no multi-generation snapshot rebuild table,
--   * deletion manifest discovery and body cleanup are both paged with a
--     persisted offset; membership is stable because the deletion gate freezes
--     the subtree against create, move, and rename operations.
--
-- Conventions:
--   * timestamps are UTC ISO-8601 strings and are always written by the store,
--   * JSON columns hold UTF-8 JSON text produced by stable stringification,
--   * node_id values are stable internal identifiers generated by the bridge /
--     server and are never re-derived from names,
--   * the tree is never hard-deleted. A removed node keeps a tombstone row
--     (lifecycle = 'deleted') so a late request for the old node_id can be
--     rejected instead of landing on a same-named rebuild.

CREATE TABLE workspace_meta (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  workspace_epoch TEXT NOT NULL,
  catalog_revision INTEGER NOT NULL DEFAULT 0,
  protocol TEXT NOT NULL DEFAULT 'rds-jbryon',
  api_version INTEGER NOT NULL DEFAULT 1
);

-- The single directory/snapshot tree (design §6.1). `kind` and `name` are
-- nullable only for deletion tombstones, which reserve a node_id that a delete
-- accepted before the node ever existed (design §11.1). Such a row has
-- lifecycle='deleted', parent_id NULL, name NULL and kind NULL.
CREATE TABLE nodes (
  node_id TEXT PRIMARY KEY,
  parent_id TEXT NULL REFERENCES nodes (node_id),
  name TEXT NULL,
  kind TEXT NULL CHECK (kind IN ('domain', 'directory', 'snapshot')),
  lifecycle TEXT NOT NULL DEFAULT 'active'
    CHECK (lifecycle IN ('active', 'deleting', 'deleted')),
  title TEXT NULL,
  default_snapshot_id TEXT NULL,
  revision INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- "Same parent, same normalized name" is unique while the node is not
-- deleted. Names are NFC-normalized in JS (contracts.normalizeName); SQL only
-- enforces the uniqueness that JS cannot enforce atomically. `deleting`
-- still reserves its name: a subtree is frozen, not renamed, during deletion.
CREATE UNIQUE INDEX nodes_sibling_name_unique
  ON nodes (COALESCE(parent_id, ''), name)
  WHERE lifecycle <> 'deleted' AND name IS NOT NULL;

CREATE INDEX nodes_parent_idx ON nodes (parent_id, lifecycle, name);
CREATE INDEX nodes_lifecycle_idx ON nodes (lifecycle, updated_at);

CREATE TABLE requests (
  request_id TEXT PRIMARY KEY,
  content_hash TEXT NOT NULL,
  operation TEXT NOT NULL,
  target_node_id TEXT NULL,
  workspace_epoch TEXT NOT NULL,
  receipt_json TEXT NOT NULL,
  effect TEXT NOT NULL DEFAULT 'pending'
    CHECK (effect IN ('pending', 'applied', 'applied_noop', 'conflict', 'cancelled', 'needs_attention')),
  target_deleted INTEGER NOT NULL DEFAULT 0 CHECK (target_deleted IN (0, 1)),
  resolved_by TEXT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX requests_target_idx ON requests (target_node_id, effect);
CREATE INDEX requests_epoch_idx ON requests (workspace_epoch, created_at);

-- Frozen event ledger (design §8). request_json is the frozen canonical
-- request and is the only place the accepted payload is stored; a controlled
-- management delete sets redacted=1 and clears request_json while keeping the
-- dedupe/identity columns (design §11.1.6).
CREATE TABLE events (
  event_seq INTEGER PRIMARY KEY AUTOINCREMENT,
  event_id TEXT NOT NULL UNIQUE,
  request_id TEXT NOT NULL UNIQUE REFERENCES requests (request_id),
  node_id TEXT NULL,
  operation TEXT NOT NULL,
  base_revision INTEGER NULL,
  depends_on_json TEXT NULL,
  request_json TEXT NULL,
  payload_hash TEXT NULL,
  -- Parent resolved at accept time. Persisted so a retry never re-resolves a
  -- path by name (design §6.1: the target is fixed after the first enqueue).
  target_parent_id TEXT NULL,
  redacted INTEGER NOT NULL DEFAULT 0 CHECK (redacted IN (0, 1)),
  created_at TEXT NOT NULL
);
CREATE INDEX events_node_seq_idx ON events (node_id, event_seq);
CREATE INDEX events_redacted_idx ON events (redacted, event_seq);

CREATE TABLE tasks (
  task_id TEXT PRIMARY KEY,
  event_seq INTEGER NOT NULL REFERENCES events (event_seq),
  state TEXT NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending', 'queued', 'processing', 'completed', 'needs_attention', 'cancelled')),
  lease_owner TEXT NULL,
  lease_epoch INTEGER NOT NULL DEFAULT 0,
  lease_until TEXT NULL,
  failure_count INTEGER NOT NULL DEFAULT 0,
  available_at TEXT NOT NULL,
  last_error TEXT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX tasks_due_idx ON tasks (state, available_at, event_seq);
CREATE INDEX tasks_event_seq_idx ON tasks (event_seq);

CREATE TABLE snapshots (
  node_id TEXT PRIMARY KEY REFERENCES nodes (node_id),
  content_json TEXT NOT NULL,
  revision INTEGER NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE snapshot_versions (
  node_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  content_json TEXT NOT NULL,
  request_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY (node_id, revision)
);
CREATE INDEX snapshot_versions_request_idx ON snapshot_versions (request_id);

CREATE TABLE conflicts (
  conflict_id TEXT PRIMARY KEY,
  node_id TEXT NOT NULL,
  request_id TEXT NOT NULL,
  base_revision INTEGER NULL,
  current_revision INTEGER NULL,
  details_json TEXT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
  resolved_by TEXT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX conflicts_node_status_idx ON conflicts (node_id, status);
CREATE INDEX conflicts_request_idx ON conflicts (request_id);

CREATE TABLE deletion_gates (
  node_id TEXT PRIMARY KEY,
  request_id TEXT NOT NULL UNIQUE,
  frozen_catalog_revision INTEGER NOT NULL,
  -- JSON: {offset:Number, complete:Boolean}; membership is frozen by the gate
  -- and traversed deterministically by node_id without storing an unbounded ID array.
  manifest_cursor TEXT NULL,
  complete INTEGER NOT NULL DEFAULT 0 CHECK (complete IN (0, 1)),
  created_at TEXT NOT NULL
);

-- Guarded-batch construction (design §8.6). A guard row must be inserted FIRST
-- in a projection batch; the triggers below abort the whole batch (D1 rolls
-- the transaction back) when the lease, catalog revision, node lifecycle or
-- snapshot revision no longer match what the handler read. The corresponding
-- conditional UPDATEs also carry the predicates, but the trigger is what makes
-- a lost race a hard database error instead of a 0-row update.
CREATE TABLE commit_guards (
  guard_id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  owner TEXT NOT NULL,
  expected_epoch INTEGER NOT NULL,
  expected_node_id TEXT NULL,
  expected_catalog_revision INTEGER NULL,
  expected_snapshot_revision INTEGER NULL,
  now_utc TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TRIGGER commit_guards_task_lease
BEFORE INSERT ON commit_guards
WHEN NOT EXISTS (
  SELECT 1 FROM tasks t
  WHERE t.task_id = NEW.task_id
    AND t.state = 'processing'
    AND t.lease_owner = NEW.owner
    AND t.lease_epoch = NEW.expected_epoch
    AND t.lease_until IS NOT NULL
    AND t.lease_until > NEW.now_utc
)
BEGIN
  SELECT RAISE(ABORT, 'stale_task_write');
END;

CREATE TRIGGER commit_guards_catalog_revision
BEFORE INSERT ON commit_guards
WHEN NEW.expected_catalog_revision IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM workspace_meta m
    WHERE m.id = 1 AND m.catalog_revision = NEW.expected_catalog_revision
  )
BEGIN
  SELECT RAISE(ABORT, 'stale_catalog_revision');
END;

-- Node lifecycle predicate: ordinary writes need an active target, directory
-- deletion finalisation needs the deleting gate holder. A create passes its
-- parent (NULL for a top-level domain).
CREATE TRIGGER commit_guards_node_lifecycle
BEFORE INSERT ON commit_guards
WHEN NEW.expected_node_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM tasks t
    JOIN events e ON e.event_seq = t.event_seq
    JOIN nodes n ON n.node_id = NEW.expected_node_id
    WHERE t.task_id = NEW.task_id
      AND (
        (e.operation = 'directory.delete' AND n.lifecycle = 'deleting')
        OR (e.operation <> 'directory.delete' AND n.lifecycle = 'active')
      )
  )
BEGIN
  SELECT RAISE(ABORT, 'stale_node_state');
END;

-- A write must not commit into a subtree whose sibling/ancestor already holds
-- a deletion gate. Establishing a gate bumps catalog_revision, so this is a
-- second, node-local line of defence behind commit_guards_catalog_revision.
CREATE TRIGGER commit_guards_no_deletion_gate
BEFORE INSERT ON commit_guards
WHEN NEW.expected_node_id IS NOT NULL
  AND EXISTS (SELECT 1 FROM deletion_gates g WHERE g.node_id = NEW.expected_node_id)
  AND NOT EXISTS (
    SELECT 1 FROM tasks t
    JOIN events e ON e.event_seq = t.event_seq
    WHERE t.task_id = NEW.task_id AND e.operation = 'directory.delete'
  )
BEGIN
  SELECT RAISE(ABORT, 'deletion_gate_blocks_write');
END;

CREATE TRIGGER commit_guards_snapshot_revision
BEFORE INSERT ON commit_guards
WHEN NEW.expected_snapshot_revision IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM snapshots s
    WHERE s.node_id = NEW.expected_node_id
      AND s.revision = NEW.expected_snapshot_revision
  )
BEGIN
  SELECT RAISE(ABORT, 'stale_snapshot_revision');
END;

-- A snapshot revision never moves backwards, whatever the caller believes.
CREATE TRIGGER snapshots_revision_monotonic
BEFORE UPDATE ON snapshots
WHEN NEW.revision < OLD.revision
BEGIN
  SELECT RAISE(ABORT, 'snapshot_revision_regression');
END;

-- Deletion freeze: once any ancestor (or the node itself) holds a gate, no
-- snapshot row may be written. This is the database-level form of "delete
-- gate rejects descendant writes" (design §11.1) and cannot be bypassed by a
-- handler that read the tree before the gate existed.
CREATE TRIGGER snapshots_blocked_by_gate
BEFORE INSERT ON snapshots
WHEN EXISTS (
  WITH RECURSIVE chain(node_id, parent_id) AS (
    SELECT node_id, parent_id FROM nodes WHERE node_id = NEW.node_id
    UNION ALL
    SELECT n.node_id, n.parent_id FROM nodes n JOIN chain c ON n.node_id = c.parent_id
    WHERE c.parent_id IS NOT NULL
  )
  SELECT 1 FROM chain c
  WHERE EXISTS (SELECT 1 FROM deletion_gates g WHERE g.node_id = c.node_id)
     OR EXISTS (
       SELECT 1 FROM nodes n2
       WHERE n2.node_id = c.node_id AND n2.lifecycle <> 'active'
     )
)
BEGIN
  SELECT RAISE(ABORT, 'deletion_gate_blocks_write');
END;

CREATE TRIGGER snapshots_update_blocked_by_gate
BEFORE UPDATE ON snapshots
WHEN EXISTS (
  WITH RECURSIVE chain(node_id, parent_id) AS (
    SELECT node_id, parent_id FROM nodes WHERE node_id = NEW.node_id
    UNION ALL
    SELECT n.node_id, n.parent_id FROM nodes n JOIN chain c ON n.node_id = c.parent_id
    WHERE c.parent_id IS NOT NULL
  )
  SELECT 1 FROM chain c
  WHERE EXISTS (SELECT 1 FROM deletion_gates g WHERE g.node_id = c.node_id)
     OR EXISTS (
       SELECT 1 FROM nodes n2
       WHERE n2.node_id = c.node_id AND n2.lifecycle <> 'active'
     )
)
BEGIN
  SELECT RAISE(ABORT, 'deletion_gate_blocks_write');
END;

-- One metadata row is seeded so that read paths have a stable shape. The
-- placeholder epoch is NOT a real workspace identity: deployment must call
-- store.initWorkspace(db, { epoch }) (or run it before serving) with a random
-- 32-hex epoch before accepting client requests.
INSERT INTO workspace_meta (id, workspace_epoch, catalog_revision, protocol, api_version)
VALUES (1, '00000000000000000000000000000000', 0, 'rds-jbryon', 1);

-- Eligibility guard for replacement requests (round 5). The batch inserts one
-- row per replacement request; the CHECK fails when the named requests are no
-- longer pending (another caller superseded them first), which rolls the whole
-- accept batch back: no request, event or task is left behind.
CREATE TABLE accept_guards (
  guard_id TEXT PRIMARY KEY,
  expected INTEGER NOT NULL,
  observed INTEGER NOT NULL,
  CHECK (observed = expected)
);

-- Atomic administrator retry: a stale/repeated retry cannot reset a task
-- without also returning its request effect to pending in the same batch.
CREATE TABLE task_retry_guards (
  guard_id TEXT PRIMARY KEY,
  expected INTEGER NOT NULL,
  observed INTEGER NOT NULL,
  CHECK (observed = expected)
);
